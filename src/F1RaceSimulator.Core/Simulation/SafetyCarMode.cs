namespace F1RaceSimulator.Core.Simulation;

/// <summary>Нейтралізація гонки після аварії або зупинки боліда на трасі.</summary>
public enum SafetyCarMode
{
    /// <summary>Зелені прапори, гонка без обмежень.</summary>
    None,

    /// <summary>
    /// Віртуальний сейфті-кар (VSC): усі пілоти знижують темп приблизно на третину,
    /// відриви між ними майже не змінюються, обгони заборонені.
    /// </summary>
    Virtual,

    /// <summary>
    /// Сейфті-кар: лідер їде за машиною безпеки, решта наздоганяє і вишиковується колоною,
    /// обгони заборонені. Піт-стоп під сейфті-каром коштує значно менше часу.
    /// </summary>
    SafetyCar
}
