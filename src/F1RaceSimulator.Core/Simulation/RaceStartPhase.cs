namespace F1RaceSimulator.Core.Simulation;

/// <summary>
/// Етап стартової процедури. Як у справжній Формулі 1, перед гонкою боліди проїжджають
/// прогрівальне коло, знову стають на свої місця на решітці, загоряються п'ять червоних
/// вогнів — і гонка починається, коли вони гаснуть.
/// </summary>
public enum RaceStartPhase
{
    /// <summary>Прогрівальне коло: повільно, у порядку решітки, без обгонів; шини й гальма прогріваються.</summary>
    FormationLap,

    /// <summary>Усі на решітці: вогні загоряються по одному щосекунди і після паузи гаснуть.</summary>
    StartLights,

    /// <summary>Вогні згасли — триває гонка.</summary>
    Racing
}
